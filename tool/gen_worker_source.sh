#!/bin/sh
# Embeds worker/src/index.js into relay_sync so `relay` can deploy it
# without wrangler. Run after editing the Worker; a test checks they match.
set -eu
root="$(cd "$(dirname "$0")/.." && pwd)"
src="$root/worker/src/index.js"
out="$root/packages/relay_sync/lib/src/worker_source.dart"
if grep -q "'''" "$src"; then echo "index.js must not contain '''" >&2; exit 1; fi
{
  echo "// GENERATED by tool/gen_worker_source.sh from worker/src/index.js. Do not edit."
  echo ""
  echo "/// The team Worker's source, deployed by [WorkerDeployer]."
  printf "const workerSource = r'''"
  cat "$src"
  echo "''';"
} > "$out"
echo "wrote $out"
