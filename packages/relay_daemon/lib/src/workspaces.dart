import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:relay_core/relay_core.dart';
import 'package:relay_git/relay_git.dart';
import 'package:relay_protocol/relay_protocol.dart';

import 'context.dart';

/// Task workspaces: one folder per task holding a git worktree for every
/// repo the task changes (all on the same branch), read-only links to the
/// project's other repos, and PROJECT.md describing how they fit together.
///
/// ```text
///   RELAY_HOME/workspaces/PROJECT_KEY/BRANCH/
///     shared/   worktree on BRANCH
///     api/      worktree on BRANCH
///     admin  -> link to the main checkout (read-only by convention)
///     PROJECT.md
/// ```
class Workspaces {
  Workspaces(this.ctx);

  final DaemonContext ctx;

  String folderFor(Task t) {
    final project = ctx.project(t.projectId);
    return p.join(ctx.paths.workspaces, project.key.toLowerCase(), t.branchName(project.key));
  }

  /// Creates (or refreshes) the task's workspace and change entries.
  /// Returns the folder an agent should start in.
  Future<String> prepare(Task task) async {
    final project = ctx.project(task.projectId);
    final branch = task.branchName(project.key);
    final folder = folderFor(task);
    Directory(folder).createSync(recursive: true);
    final touched = ctx.touchedRepos(task);
    if (touched.isEmpty) {
      throw RpcError(RpcError.invalidParams, '${project.name} has no repositories yet. Add one under Repos.');
    }
    final all = ctx.reposOf(task.projectId);
    for (final repo in all) {
      final source = repo.pathOn(ctx.deviceId);
      final target = p.join(folder, _dirName(repo));
      if (touched.any((r) => r.id == repo.id)) {
        if (source == null || !await ctx.git.isRepo(source)) {
          throw RpcError(RpcError.invalidParams, '${repo.name} is not cloned on this Mac.');
        }
        final link = Link(target);
        if (link.existsSync()) link.deleteSync();
        await ctx.git.worktreeAdd(source, target, branch, base: repo.baseBranch);
        _ensureChange(task, repo, branch, target);
      } else if (source != null && Directory(source).existsSync()) {
        final link = Link(target);
        if (!link.existsSync() && !Directory(target).existsSync()) link.createSync(source);
      }
    }
    File(p.join(folder, 'PROJECT.md')).writeAsStringSync(projectMap(task));
    return touched.length == 1 ? p.join(folder, _dirName(touched.first)) : folder;
  }

  String _dirName(Repo r) => r.name.replaceAll(RegExp(r'[^A-Za-z0-9._-]'), '-');

  void _ensureChange(Task task, Repo repo, String branch, String worktree) {
    final existing = changesOf(task.id).where((c) => c.repoId == repo.id);
    if (existing.isNotEmpty) {
      if (existing.first.worktreePath != worktree) {
        ctx.store.patch<ChangeEntry>(Kind.change, existing.first.id, {'worktreePath': worktree});
      }
      return;
    }
    ctx.store.create<ChangeEntry>(Kind.change, {
      'taskId': task.id,
      'repoId': repo.id,
      'projectId': task.projectId,
      'branch': branch,
      'worktreePath': worktree,
      'status': 'pending',
    });
  }

  List<ChangeEntry> changesOf(String taskId) => ctx.store.list<ChangeEntry>(Kind.change, taskId: taskId);

  /// The repo map agents read: what each repo is, how they depend on each
  /// other, which ones this task may change, and the merge order.
  String projectMap(Task task) {
    final project = ctx.project(task.projectId);
    final all = ctx.reposOf(task.projectId);
    final touched = ctx.touchedRepos(task).map((r) => r.id).toSet();
    final byId = {for (final r in all) r.id: r};
    final b = StringBuffer()
      ..writeln('# ${project.name} — workspace for ${task.displayKey(project.key)}')
      ..writeln()
      ..writeln('Generated by Relay. Branch `${task.branchName(project.key)}` in every repo you may change.')
      ..writeln()
      ..writeln('| Folder | Role | Stack | Base | You may change | Depends on | Test |')
      ..writeln('|---|---|---|---|---|---|---|');
    for (final r in all) {
      final deps = r.dependsOn.map((d) => byId[d]?.name ?? d).join(', ');
      b.writeln('| `${_dirName(r)}/` | ${r.role} | ${r.stack} | ${r.baseBranch} | '
          '${touched.contains(r.id) ? 'yes' : 'no (read-only link)'} | $deps | ${r.testCommand ?? ''} |');
    }
    final contracts = all.where((r) => r.contractPaths.isNotEmpty).toList();
    if (contracts.isNotEmpty) {
      b
        ..writeln()
        ..writeln('## Contracts');
      for (final r in contracts) {
        for (final c in r.contractPaths) {
          b.writeln('- `${_dirName(r)}/$c` — repos that depend on ${r.name} must match it. Change it first.');
        }
      }
    }
    b
      ..writeln()
      ..writeln('## Merge order')
      ..writeln(mergeSteps(all).map((s) => s.map((r) => r.name).join(', ')).join(' → '))
      ..writeln()
      ..writeln('Commit your work in each repo you change. End commit messages with:')
      ..writeln('```')
      ..writeln('Relay-Task: ${task.displayKey(project.key)}')
      ..writeln('```');
    return b.toString();
  }

  static List<List<Repo>> mergeSteps(List<Repo> repos) {
    final steps = <int, List<Repo>>{};
    for (final r in repos) {
      steps.putIfAbsent(r.mergeStep, () => []).add(r);
    }
    final keys = steps.keys.toList()..sort();
    return [for (final k in keys) steps[k]!];
  }

  /// Commits leftover agent edits and refreshes each change entry's stats.
  /// [settle] is set when a run ends, so `running` entries become ready.
  Future<void> refresh(Task task, {String? agentId, bool commit = false, bool settle = false}) async {
    final project = ctx.project(task.projectId);
    for (final c in changesOf(task.id)) {
      final wt = c.worktreePath;
      if (wt == null || !Directory(wt).existsSync()) continue;
      final repo = ctx.store.get<Repo>(Kind.repo, c.repoId);
      if (repo == null) continue;
      if (commit) {
        final agentName = agentId == null ? 'Relay' : (ctx.agent(agentId)?.name ?? agentId);
        try {
          await ctx.git.commitAll(
            wt,
            '${task.title}\n\nWork by $agentName in Relay.\n\nRelay-Task: ${task.displayKey(project.key)}\n'
            '${agentId != null ? 'Relay-Agent: $agentId\n' : ''}',
          );
        } on GitException catch (e) {
          ctx.notice('Could not commit in ${repo.name}: ${e.stderr.trim()}', level: 'warning');
        }
      }
      final stat = await ctx.git.diffStat(wt, repo.baseBranch);
      final patch = <String, Object?>{
        'additions': stat.additions,
        'deletions': stat.deletions,
        'filesChanged': stat.files,
        'agentId': ?agentId,
      };
      if (c.status != 'merged' && (settle || c.status != 'running')) {
        patch['status'] = stat.files > 0 ? 'ready' : 'pending';
      }
      ctx.store.patch<ChangeEntry>(Kind.change, c.id, patch);
      await _checkContracts(task, repo, c, stat);
    }
  }

  Future<void> markRunning(Task task, String agentId) async {
    for (final c in changesOf(task.id)) {
      if (c.status != 'merged') {
        ctx.store.patch<ChangeEntry>(Kind.change, c.id, {'status': 'running', 'agentId': agentId});
      }
    }
  }

  /// When a repo's contract file changed on this task's branch, tell every
  /// agent working in a repo that depends on it (once per change).
  Future<void> _checkContracts(Task task, Repo repo, ChangeEntry change, DiffStat stat) async {
    if (repo.contractPaths.isEmpty) return;
    final changed = stat.perFile
        .map((f) => f['path'] as String)
        .where((path) => repo.contractPaths.any((c) => path == c || path.endsWith('/$c') || path.startsWith(c)))
        .toList();
    if (changed.isEmpty) return;
    final signature = '${changed.join(',')}:${stat.additions}:${stat.deletions}';
    if (change.data['contractNotified'] == signature) return;
    ctx.store.patch<ChangeEntry>(Kind.change, change.id, {'contractNotified': signature});
    final dependents = ctx.reposOf(task.projectId).where((r) => r.dependsOn.contains(repo.id)).map((r) => r.name).toList();
    final text = 'Contract changed in ${repo.name}: ${changed.join(', ')}. '
        '${dependents.isEmpty ? '' : 'Repos that depend on it: ${dependents.join(', ')}. '}'
        'Re-read it before continuing.';
    ctx.store.create<Comment>(Kind.comment, {
      'taskId': task.id,
      'authorKind': 'system',
      'author': 'Relay',
      'body': text,
      'contract': true,
    });
    for (final l in contractListeners) {
      l(task, text);
    }
  }

  /// Supervisor hooks in here to steer running agents.
  final contractListeners = <void Function(Task task, String text)>[];

  /// Merges the task's ready changes into each repo's base branch, step by
  /// step in merge order. Stops at the first repo that can't merge.
  Future<List<Map<String, Object?>>> merge(Task task, {String? repoId}) async {
    final project = ctx.project(task.projectId);
    final changes = {for (final c in changesOf(task.id)) c.repoId: c};
    final results = <Map<String, Object?>>[];
    for (final step in mergeSteps(ctx.reposOf(task.projectId))) {
      for (final repo in step) {
        final c = changes[repo.id];
        if (c == null || c.status == 'merged') continue;
        if (repoId != null && repo.id != repoId) continue;
        final source = repo.pathOn(ctx.deviceId);
        if (source == null) {
          results.add({'repo': repo.name, 'ok': false, 'error': 'not cloned here'});
          return results;
        }
        if (c.filesChanged == 0 && c.additions == 0 && c.deletions == 0) {
          ctx.store.patch<ChangeEntry>(Kind.change, c.id, {'status': 'merged', 'mergedBy': 'nothing to merge'});
          continue;
        }
        try {
          final current = await ctx.git.currentBranch(source);
          if (current != repo.baseBranch) {
            throw GitException(['merge'], 1, '${repo.name} is on $current, not ${repo.baseBranch}.');
          }
          final head = await ctx.git.mergeInto(
            source,
            c.branch,
            message: 'Merge ${task.displayKey(project.key)}: ${task.title}\n\nRelay-Task: ${task.displayKey(project.key)}',
          );
          ctx.store.patch<ChangeEntry>(Kind.change, c.id, {
            'status': 'merged',
            'mergedBy': ctx.setting('userName', 'You'),
            'mergeCommit': head,
          });
          results.add({'repo': repo.name, 'ok': true, 'commit': head});
        } on GitException catch (e) {
          ctx.store.patch<ChangeEntry>(Kind.change, c.id, {'status': 'failed', 'checks': e.stderr.trim()});
          results.add({'repo': repo.name, 'ok': false, 'error': e.stderr.trim()});
          return results;
        }
      }
      if (repoId != null) break;
    }
    final remaining = changesOf(task.id).where((c) => c.status != 'merged');
    if (remaining.isEmpty) {
      ctx.store.patch<Task>(Kind.task, task.id, {'status': TaskStatus.done, 'attention': null});
    }
    return results;
  }

  /// Removes the task's worktrees and folder (after merge or on request).
  Future<void> cleanup(Task task) async {
    for (final c in changesOf(task.id)) {
      final repo = ctx.store.get<Repo>(Kind.repo, c.repoId);
      final source = repo?.pathOn(ctx.deviceId);
      if (source != null && c.worktreePath != null) {
        await ctx.git.worktreeRemove(source, c.worktreePath!, force: true);
      }
    }
    final dir = Directory(folderFor(task));
    if (dir.existsSync()) dir.deleteSync(recursive: true);
  }
}
